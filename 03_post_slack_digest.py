"""
Script 3 of 4: post to Slack (runs after score/route).

Reads output/lead_summary.json (from script 2), turns it into a Slack message
(Block Kit), and posts it with an incoming webhook.

    python 03_post_slack_digest.py            # dry run unless SLACK_WEBHOOK_URL is set
    python 03_post_slack_digest.py --dry-run  # always just print, never post

No SLACK_WEBHOOK_URL? It prints the exact JSON it would send and saves it to
output/slack_payload.json, so you can paste it into Slack's Block Kit Builder.
With ANTHROPIC_API_KEY set, Claude writes the two-line headline; without it, a
built-in template does.
"""
import argparse
import json
import os
from pathlib import Path

import requests

try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    pass

SUMMARY = Path("output/lead_summary.json")
ROUTING = Path("output/routing_summary.json")
PAYLOAD_OUT = Path("output/slack_payload.json")
DEFAULT_MODEL = "claude-sonnet-5-5"
MAX_LISTED = 5  # keep the Slack message short; the CSV has the rest


def top(d: dict, n: int = 3) -> str:
    return ", ".join(f"{k} {v}" for k, v in list(d.items())[:n]) or "none"


def template_headline(s: dict, routing: dict | None = None) -> str:
    """The no-API-key version: plain string formatting."""
    flagged = len(s["needs_attention"])
    unassigned = s["by_owner"].get("Unassigned", 0)
    line1 = f"{s['total']} new contacts this week from {len(s['by_source'])} sources: {top(s['by_source'], 4)}."
    if routing:
        routes = routing.get("by_route", {})
        line2 = (f"Routed {routing.get('crm_ready', 0)} CRM-ready "
                 f"(ae_review {routes.get('ae_review', 0)}, sdr {routes.get('sdr_sequence', 0)}, "
                 f"nurture {routes.get('nurture', 0)}); {routing.get('review_queue', flagged)} on the review queue.")
    else:
        line2 = (f"{flagged} need a fix before routing" + (f", including {unassigned} with no owner." if unassigned else "."))
    return f"{line1}\n{line2}"


def claude_headline(s: dict) -> str | None:
    """Ask Claude for a two-line headline. Returns None if anything goes wrong."""
    key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if not key:
        return None
    try:
        import anthropic
        client = anthropic.Anthropic(api_key=key)
        prompt = ("You write the top two lines of a weekly new-lead Slack digest for a RevOps team. "
                  "Use only the numbers in this JSON, invent nothing, no emoji, under 45 words, "
                  "line 1 = volume and sources, line 2 = what needs fixing.\n\n"
                  + json.dumps({k: s[k] for k in ("total", "by_lifecycle", "by_source", "by_owner", "flag_counts")}))
        resp = client.messages.create(model=os.environ.get("ANTHROPIC_MODEL", DEFAULT_MODEL),
                                      max_tokens=150, messages=[{"role": "user", "content": prompt}])
        return resp.content[0].text.strip()
    except Exception as exc:  # network, bad key, wrong model name…
        print(f"Claude call failed ({exc.__class__.__name__}); using the template headline instead.")
        return None


def build_payload(s: dict, headline: str) -> dict:
    portal = os.environ.get("HUBSPOT_PORTAL_ID", "").strip()
    region = os.environ.get("HUBSPOT_APP_DOMAIN", "app.hubspot.com").strip()

    def contact_link(c: dict) -> str:
        label = c["name"] + (f" ({c['company']})" if c["company"] else "")
        if portal:
            return f"<https://{region}/contacts/{portal}/record/0-1/{c['hubspot_id']}|{label}>"
        return label

    lines = [f"• {contact_link(c)}: {c['flags']}" for c in s["needs_attention"][:MAX_LISTED]]
    more = len(s["needs_attention"]) - MAX_LISTED
    if more > 0:
        lines.append(f"…and {more} more in new_leads.csv")
    mock_note = " (sample data)" if s.get("mode") == "mock" else ""

    return {
        "text": headline.replace("\n", " "),  # fallback text for notifications
        "blocks": [
            {"type": "header", "text": {"type": "plain_text", "text": f"Weekly new-lead digest{mock_note}"}},
            {"type": "section", "text": {"type": "mrkdwn", "text": headline}},
            {"type": "section", "fields": [
                {"type": "mrkdwn", "text": f"*By lifecycle*\n{top(s['by_lifecycle'], 5)}"},
                {"type": "mrkdwn", "text": f"*By owner*\n{top(s['by_owner'], 5)}"},
            ]},
            {"type": "section", "text": {"type": "mrkdwn",
                                         "text": "*Needs attention*\n" + ("\n".join(lines) or "Nothing flagged.")}},
            {"type": "context", "elements": [{"type": "mrkdwn",
                                              "text": f"{s['date_range'][0]} to {s['date_range'][-1]} · generated by python-for-gtm-basics"
                                              if s.get("date_range") else "generated by python-for-gtm-basics"}]},
        ],
    }


def post(webhook: str, payload: dict) -> None:
    resp = requests.post(webhook, json=payload, timeout=15)
    # Slack webhooks answer 200 with the body "ok"; anything else is an error message.
    if resp.status_code != 200 or resp.text.strip() != "ok":
        raise SystemExit(f"Slack rejected the message ({resp.status_code}): {resp.text[:200]}")
    print("Posted to Slack.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Post the lead digest to Slack.")
    parser.add_argument("--dry-run", action="store_true", help="print the payload instead of posting")
    args = parser.parse_args()

    if not SUMMARY.exists():
        raise SystemExit(f"{SUMMARY} not found. Run python 02_transform_contacts.py first.")
    s = json.loads(SUMMARY.read_text())
    routing = json.loads(ROUTING.read_text()) if ROUTING.exists() else None

    headline = claude_headline(s)
    source = "Claude" if headline else "template"
    headline = headline or template_headline(s, routing)
    payload = build_payload(s, headline)

    PAYLOAD_OUT.write_text(json.dumps(payload, indent=2, ensure_ascii=False))
    print(f"Headline ({source}):\n{headline}\n")

    webhook = os.environ.get("SLACK_WEBHOOK_URL", "").strip()
    if webhook and not args.dry_run:
        post(webhook, payload)
    else:
        why = "--dry-run" if args.dry_run else "no SLACK_WEBHOOK_URL set"
        print(f"Dry run ({why}). This is what would be sent, also saved to {PAYLOAD_OUT}:\n")
        print(json.dumps(payload, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
